package api

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"
	"testing"
)

// handoff-ui H-8: ErrorCodes (errcodes.go) is the catalogue of every error
// code the backend can return. This test greps internal/ with the same
// patterns as web/scripts/check-i18n.mjs and fails when the catalogue is
// stale. Regenerate with: BPANEL_WRITE_ERRCODES=1 go test ./internal/api -run TestErrorCodeCatalogue
func TestErrorCodeCatalogue(t *testing.T) {
	pats := []*regexp.Regexp{
		regexp.MustCompile(`\b(?:bad|badMsg|conflict|badField)\(\s*"([a-z0-9_]+)"`),
		regexp.MustCompile(`Code:\s*"([a-z0-9_]+)"`),
		regexp.MustCompile(`\berrf\(\s*"([a-z0-9_]+)"`),
		regexp.MustCompile(`\bfail\(\s*"([a-z0-9_]+)"`),
		regexp.MustCompile(`errors\.New\(\s*"([a-z0-9_]+)"\)`),
		regexp.MustCompile(`fmt\.Errorf\(\s*"([a-z0-9_]+)"\)`),
	}
	settingsSet := regexp.MustCompile(`set\("([a-z_]+)", in\.`)
	codes := map[string]bool{}
	err := filepath.WalkDir("..", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(p, ".go") || strings.HasSuffix(p, "_test.go") || strings.HasSuffix(p, "errcodes.go") {
			return err
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		s := string(b)
		for _, re := range pats {
			for _, m := range re.FindAllStringSubmatch(s, -1) {
				c := m[1]
				if !strings.HasSuffix(c, "_") && (strings.Contains(c, "_") || c == "refused" || c == "forbidden") {
					codes[c] = true
				}
			}
		}
		if strings.Contains(s, `bad("invalid_" + k)`) {
			for _, m := range settingsSet.FindAllStringSubmatch(s, -1) {
				codes["invalid_"+m[1]] = true
			}
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	var want []string
	for c := range codes {
		want = append(want, c)
	}
	sort.Strings(want)
	if os.Getenv("BPANEL_WRITE_ERRCODES") == "1" {
		var b strings.Builder
		b.WriteString("// Code generated by TestErrorCodeCatalogue; DO NOT EDIT.\n// Regenerate: BPANEL_WRITE_ERRCODES=1 go test ./internal/api -run TestErrorCodeCatalogue\n\npackage api\n\n")
		b.WriteString("// ErrorCodes is every error code the API and the agent can return (handoff-ui H-8).\n// The UI's i18n check requires an EN+TR text for each.\nvar ErrorCodes = []string{\n")
		for _, c := range want {
			fmt.Fprintf(&b, "\t%q,\n", c)
		}
		b.WriteString("}\n")
		if err := os.WriteFile("errcodes.go", []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got := slices.Clone(ErrorCodes)
	sort.Strings(got)
	if !slices.Equal(got, want) {
		t.Fatalf("errcodes.go is stale; regenerate with BPANEL_WRITE_ERRCODES=1.\nmissing: %v\nextra: %v", diff(want, got), diff(got, want))
	}
}

func diff(a, b []string) []string {
	var out []string
	for _, x := range a {
		if !slices.Contains(b, x) {
			out = append(out, x)
		}
	}
	return out
}
